const languageSwitcher = document.getElementById('language-switcher');
const navLinks = document.querySelectorAll('.nav-links a');

function applyLanguage(lang) {
  if (!translations[lang]) {
    lang = 'en';
  }
  const messages = translations[lang] || translations['en'];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  const textNodes = document.querySelectorAll('[data-i18n]');
  textNodes.forEach(node => {
    if (!node) return;
    const key = node.getAttribute('data-i18n');
    if (messages[key]) {
      node.textContent = messages[key];
    }
  });
  if (languageSwitcher) {
    languageSwitcher.value = lang;
  }
  try {
    localStorage.setItem('oaif-lang', lang);
  } catch (e) {
    console.warn('Failed to save language preference:', e);
  }
}

function initLanguage() {
  let saved = null;
  try {
    saved = localStorage.getItem('oaif-lang');
  } catch (e) {
    console.warn('Failed to read language preference:', e);
  }
  const fallback = 'en';
  const preferred = (saved && translations[saved]) ? saved : fallback;
  languageSwitcher.value = preferred;
  applyLanguage(preferred);
}

if (languageSwitcher) {
  languageSwitcher.addEventListener('change', event => {
    applyLanguage(event.target.value);
  });

  initLanguage();
}

function setupSmoothScroll() {
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');

  navLinks.forEach(link => {
    link.addEventListener('click', event => {
      const targetId = link.getAttribute('href');
      if (!targetId || !targetId.startsWith('#')) return;

      const section = document.querySelector(targetId);
      if (!section) return;

      event.preventDefault();
      section.scrollIntoView({ behavior: prefersReducedMotion.matches ? 'auto' : 'smooth' });
      setActiveNav(targetId);
    });
  });
}

function setActiveNav(id) {
  navLinks.forEach(link => {
    link.classList.toggle('active', link.getAttribute('href') === id);
  });
}

function setupSectionObserver() {
  if (!('IntersectionObserver' in window)) return;

  const sections = [...document.querySelectorAll('main section')];
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const id = `#${entry.target.id}`;
        setActiveNav(id);
      }
    });
  }, { rootMargin: '-40% 0px -40% 0px', threshold: 0.25 });

  sections.forEach(section => observer.observe(section));
}

setupSmoothScroll();
setupSectionObserver();

// Mobile menu toggle
function setupMobileMenu() {
  const menuToggle = document.querySelector('.mobile-menu-toggle');
  const navLinks = document.querySelector('.nav-links');
  const headerActions = document.querySelector('.header-actions');
  const dropdownItems = document.querySelectorAll('.nav-item--dropdown');

  if (!menuToggle || !navLinks) return;

  // Toggle mobile menu
  menuToggle.addEventListener('click', () => {
    const isActive = navLinks.classList.toggle('active');
    menuToggle.classList.toggle('active');
    menuToggle.setAttribute('aria-expanded', isActive);
  });

  // Handle dropdown clicks on mobile
  dropdownItems.forEach(item => {
    const link = item.querySelector('a');
    if (!link) return;

    link.addEventListener('click', (e) => {
      // Only prevent default on mobile
      if (window.innerWidth <= 960) {
        e.preventDefault();
        item.classList.toggle('active');
      }
    });
  });

  // Close menu when clicking nav links
  const allNavLinks = navLinks.querySelectorAll('a:not(.nav-item--dropdown > a)');
  allNavLinks.forEach(link => {
    link.addEventListener('click', () => {
      if (window.innerWidth <= 960) {
        navLinks.classList.remove('active');
        menuToggle.classList.remove('active');
        menuToggle.setAttribute('aria-expanded', 'false');
      }
    });
  });

  // Close menu when clicking action buttons
  if (headerActions) {
    const actionButtons = headerActions.querySelectorAll('.btn');
    actionButtons.forEach(button => {
      button.addEventListener('click', () => {
        if (window.innerWidth <= 960) {
          navLinks.classList.remove('active');
          menuToggle.classList.remove('active');
          menuToggle.setAttribute('aria-expanded', 'false');
        }
      });
    });
  }

  // Close menu when clicking outside
  document.addEventListener('click', (e) => {
    if (window.innerWidth <= 960 && 
        !menuToggle.contains(e.target) && 
        !navLinks.contains(e.target) &&
        (!headerActions || !headerActions.contains(e.target)) &&
        navLinks.classList.contains('active')) {
      navLinks.classList.remove('active');
      menuToggle.classList.remove('active');
      menuToggle.setAttribute('aria-expanded', 'false');
    }
  });
}

setupMobileMenu();
